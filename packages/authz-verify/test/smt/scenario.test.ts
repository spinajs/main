import 'mocha';
import { expect } from 'chai';

import { policyHash } from '@spinajs/authz-ir';
import { minimize, outcome, reachers, renderScenario } from '../../src/index.js';
import type { Scenario } from '../../src/index.js';
import { docsIR } from '../fixtures/docs.js';
import { invoicesIR } from '../fixtures/invoices.js';

describe('minimize', () => {
  it('drops every tuple and context value the expected answers do not need', async () => {
    const ir = invoicesIR();
    const [, accountant] = reachers(ir, 'invoice:read');
    const noisy: Scenario = {
      ...accountant.witness,
      tuples: [...accountant.witness.tuples, { object: { type: 'org', id: 'o2' }, relation: 'accountant', subject: { type: 'user', id: 'u1' } }, { object: { type: 'group', id: 'g1' }, relation: 'member', subject: { type: 'user', id: 'u1' } }],
      context: { resource: { status: 'open' }, env: { hour: 3 } },
    };
    const small = await minimize(ir, noisy, { 'invoice:read': 'allow' });
    expect(small).to.deep.equal(accountant.witness);
  });

  it('keeps the context a caveat needs', async () => {
    const ir = docsIR();
    const s: Scenario = { principal: { type: 'user', id: 'u1' }, resource: { type: 'doc', id: 'd1' }, tuples: [{ object: { type: 'doc', id: 'd1' }, relation: 'editor', subject: { type: 'user', id: 'u1' } }], context: { resource: { status: 'frozen' }, env: { hour: 3 } } };
    const small = await minimize(ir, s, { 'doc:update': 'allow', 'doc:publish': 'deny' });
    expect(small.context).to.deep.equal({ resource: { status: 'frozen' } });
    expect(await outcome(ir, small, ['doc:update', 'doc:publish'])).to.deep.equal({ 'doc:update': 'allow', 'doc:publish': 'deny' });
  });
});

describe('renderScenario', () => {
  it('writes a counterexample as an .authz.yaml scenario', () => {
    const ir = invoicesIR();
    const [, accountant] = reachers(ir, 'invoice:read');
    const yaml = renderScenario(ir, 'onlyVia(invoice:read, [invoice#owner])', {
      ...accountant.witness,
      tuples: [...accountant.witness.tuples, { object: { type: 'invoice', id: 'i1' }, relation: 'frozen', subject: { type: 'user', id: '*', caveat: { name: 'status_is_frozen' } } }],
      context: { resource: { status: 'open' } },
      outcome: { 'invoice:read': 'allow' },
    });
    expect(yaml).to.equal(
      [
        '# Reproduces onlyVia(invoice:read, [invoice#owner]); generated by @spinajs/authz-verify.',
        'name: "onlyVia(invoice:read, [invoice#owner])"',
        `policyHash: "${policyHash(ir)}"`,
        'tuples:',
        '  - object: "invoice:i1"',
        '    relation: "parent"',
        '    subject: "project:p1"',
        '  - object: "project:p1"',
        '    relation: "parent"',
        '    subject: "org:o1"',
        '  - object: "org:o1"',
        '    relation: "accountant"',
        '    subject: "user:u1"',
        '  - object: "invoice:i1"',
        '    relation: "frozen"',
        '    subject: "user:*"',
        '    caveat: "status_is_frozen"',
        'context: {"resource":{"status":"open"}}',
        'checks:',
        '  - principal: "user:u1"',
        '    permission: "invoice:read"',
        '    resource: "invoice:i1"',
        '    expect: allow',
        '',
      ].join('\n'),
    );
    for (const line of yaml.split('\n').filter((l) => /^\s*(- )?\w+: ["{]/.test(l))) expect(() => JSON.parse(line.slice(line.indexOf(': ') + 2)) as unknown, line).not.to.throw();
  });
});
