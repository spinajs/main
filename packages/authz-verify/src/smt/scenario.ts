import { policyHash } from '@spinajs/authz-ir';
import type { PolicyIR, TupleSubjectRef } from '@spinajs/authz-ir';

import type { Counterexample } from '../verdict.js';

const ref = (o: { type: string; id: string }): string => `${o.type}:${o.id}`;
const subject = (s: TupleSubjectRef): string => `${ref(s)}${s.relation === undefined ? '' : `#${s.relation}`}`;
// JSON strings and flow mappings are valid YAML, which keeps quoting rules out of this file.
const q = (v: unknown): string => JSON.stringify(v);

/**
 * A counterexample as a native `.authz.yaml` scenario: the policy hash it was found on, the tuples (column
 * relations included, as tuples of their relation), the request context and one check per permission with the
 * answer the reference evaluator gave, so the scenario runner (Z6) reproduces it against the real engine.
 */
export function renderScenario(ir: PolicyIR, name: string, cx: Counterexample): string {
  const lines = [`# Reproduces ${name}; generated by @spinajs/authz-verify.`, `name: ${q(name)}`, `policyHash: ${q(policyHash(ir))}`];
  lines.push(cx.tuples.length === 0 ? 'tuples: []' : 'tuples:');
  for (const t of cx.tuples) {
    lines.push(`  - object: ${q(ref(t.object))}`, `    relation: ${q(t.relation)}`, `    subject: ${q(subject(t.subject))}`);
    if (t.subject.caveat !== undefined) lines.push(`    caveat: ${q(t.subject.caveat.name)}`);
    if (t.subject.caveat?.context !== undefined) lines.push(`    caveatContext: ${q(t.subject.caveat.context)}`);
  }
  if (cx.context !== undefined) lines.push(`context: ${q(cx.context)}`);
  lines.push('checks:');
  for (const [permission, truth] of Object.entries(cx.outcome)) {
    lines.push(`  - principal: ${q(ref(cx.principal))}`, `    permission: ${q(permission)}`, `    resource: ${q(ref(cx.resource))}`, `    expect: ${truth}`);
  }
  return `${lines.join('\n')}\n`;
}
