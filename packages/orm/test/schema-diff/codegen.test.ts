import { expect } from 'chai';
import { RawQuery } from '../../src/builders/raw.js';
import { generateMigration, isActionable, planMigration } from '../../src/schema-diff/codegen.js';
import type { SchemaChange, TargetTable } from '../../src/schema-diff/types.js';
import { live } from './fixture.js';

const NOW = new Date(2026, 10, 3, 10, 20, 30);

const tags: TargetTable = {
  name: 'tags',
  exhaustive: false,
  models: ['Tag'],
  indexes: [{ columns: ['Name', 'Id'], unique: false }],
  foreignKeys: [],
  columns: [
    { name: 'Id', primary: true, nullable: false, sql: { family: 'integer', inferred: true } },
    { name: 'Name', primary: false, nullable: false, sql: { family: 'text', length: 50, unique: true } },
  ],
};

const changes: SchemaChange[] = [
  { kind: 'dropColumn', table: 'posts', detail: { column: 'Legacy' }, destructive: true, reason: 'posts.Legacy was removed from the models since --base' },
  { kind: 'addColumn', table: 'posts', detail: { name: 'Summary', primary: false, nullable: true, sql: { family: 'text', inferred: true } }, destructive: false },
  { kind: 'createTable', table: 'tags', detail: tags, destructive: false },
  { kind: 'unmanaged', table: 'posts', detail: { column: 'Old', nullable: true, hasDefault: false }, destructive: false },
];

describe('generateMigration', () => {
  it('writes creates first, then adds, then DESTRUCTIVE steps as comments, with the inverse in down()', () => {
    const out = generateMigration(changes, { name: 'Shop', connection: 'default', allowDestructive: false, now: NOW });
    expect(out.fileName).to.equal('Shop_2026_11_03_10_20_30.ts');
    expect(out.source).to.equal(
      [
        "import { Migration, type OrmDriver, OrmMigration } from '@spinajs/orm';",
        '',
        '/**',
        ' * Generated by `spinajs migrate-diff` from the app manifest. Review it before it runs.',
        ' */',
        "@Migration('default')",
        'export class Shop_2026_11_03_10_20_30 extends OrmMigration {',
        '  public async up(connection: OrmDriver): Promise<void> {',
        "    await connection.schema().createTable('tags', (table) => {",
        "      table.int('Id').primaryKey().autoIncrement().notNull();",
        "      table.string('Name', 50).notNull().unique();",
        '    });',
        "    await connection.index().table('tags').name('ix_tags_Name_Id').columns(['Name', 'Id']);",
        "    await connection.schema().alterTable('posts', (table) => {",
        "      table.text('Summary');",
        '    });',
        '    // DESTRUCTIVE: posts.Legacy was removed from the models since --base (pass --allow-destructive to run it)',
        "    // await connection.schema().alterTable('posts', (table) => {",
        "    //   table.dropColumn('Legacy');",
        '    // });',
        '  }',
        '',
        '  public async down(connection: OrmDriver): Promise<void> {',
        "    await connection.schema().alterTable('posts', (table) => {",
        "      table.dropColumn('Summary');",
        '    });',
        "    await connection.schema().dropTable('tags');",
        '  }',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('writes DESTRUCTIVE steps as code with allowDestructive, and an unused down() parameter as _connection', () => {
    const { source } = generateMigration([changes[0]], { name: 'Drop', connection: 'default', allowDestructive: true, now: NOW });
    expect(source).to.include(
      [
        '    // DESTRUCTIVE: posts.Legacy was removed from the models since --base',
        "    await connection.schema().alterTable('posts', (table) => {",
        "      table.dropColumn('Legacy');",
        '    });',
      ].join('\n'),
    );
    expect(source).to.include('  public async down(_connection: OrmDriver): Promise<void> {\n  }');
  });

  it('modifies a column under its reason, renders defaults, and imports RawQuery for a raw one', () => {
    const { source } = generateMigration(
      [
        { kind: 'alterColumn', table: 'posts', detail: { column: { name: 'Title', primary: false, nullable: true, sql: { family: 'text', length: 200 } }, from: live('Title', 'varchar', { MaxLength: 100 }) }, destructive: false, reason: 'posts.Title: length 100 → 200' },
        { kind: 'addColumn', table: 'posts', detail: { name: 'Token', primary: false, nullable: false, sql: { family: 'uuid', default: { raw: 'gen_random_uuid()' } } }, destructive: false },
        { kind: 'addColumn', table: 'posts', detail: { name: 'Seen', primary: false, nullable: false, sql: { family: 'datetime', default: { raw: 'CURRENT_TIMESTAMP' } } }, destructive: false },
        { kind: 'addColumn', table: 'posts', detail: { name: 'Live', primary: false, nullable: false, sql: { family: 'boolean', default: true } }, destructive: false },
      ],
      { name: 'Alter', connection: 'default', allowDestructive: false, now: NOW },
    );
    expect(source.split('\n')[0]).to.equal("import { Migration, type OrmDriver, OrmMigration, RawQuery } from '@spinajs/orm';");
    expect(source).to.include("    // posts.Title: length 100 → 200\n    await connection.schema().alterTable('posts', (table) => {\n      table.string('Title', 200).modify();\n    });");
    expect(source).to.include("table.binary('Token', 16).notNull().default().raw(RawQuery.create('gen_random_uuid()'));");
    expect(source).to.include("table.dateTime('Seen').notNull().default().dateTime();");
    expect(source).to.include("table.boolean('Live').notNull().default().value(1);");
  });

  it('keeps the live NOT NULL and DEFAULT that a family-only change on an inferred column does not state (Q16)', () => {
    const quantity = { name: 'Quantity', primary: false, nullable: false, sql: { family: 'integer' as const, inferred: true } };
    const { source } = generateMigration(
      [{ kind: 'alterColumn', table: 'posts', detail: { column: quantity, from: live('Quantity', 'varchar', { Nullable: false, DefaultValue: '0' }) }, destructive: true, reason: 'posts.Quantity: type varchar → integer' }],
      { name: 'Keep', connection: 'default', allowDestructive: true, now: NOW },
    );
    expect(source).to.include("table.int('Quantity').modify().notNull().default().value('0');");
    const relaxed = generateMigration(
      [{ kind: 'alterColumn', table: 'posts', detail: { column: quantity, from: live('Quantity', 'varchar', { Nullable: true }) }, destructive: true, reason: 'posts.Quantity: type varchar → integer' }],
      { name: 'Keep', connection: 'default', allowDestructive: true, now: NOW },
    );
    expect(relaxed.source).to.include("table.int('Quantity').modify();");
  });

  it('keeps a live expression default and the live length on modify (Q16)', () => {
    const { source } = generateMigration(
      [
        { kind: 'alterColumn', table: 'posts', detail: { column: { name: 'Seen', primary: false, nullable: false, sql: { family: 'datetime' } }, from: live('Seen', 'timestamptz', { Nullable: true, DefaultValue: RawQuery.create('CURRENT_TIMESTAMP') }) }, destructive: false, reason: 'posts.Seen: NOT NULL' },
        { kind: 'alterColumn', table: 'posts', detail: { column: { name: 'Counter', primary: false, nullable: false, sql: { family: 'bigint', inferred: true } }, from: live('Counter', 'int4', { DefaultValue: RawQuery.create("nextval('posts_counter_seq'::regclass)") }) }, destructive: false, reason: 'posts.Counter: type int4 → bigint' },
        { kind: 'alterColumn', table: 'posts', detail: { column: { name: 'Title', primary: false, nullable: true, sql: { family: 'text' } }, from: live('Title', 'varchar', { MaxLength: 100 }) }, destructive: false, reason: 'posts.Title: NULL allowed' },
      ],
      { name: 'Keep', connection: 'default', allowDestructive: false, now: NOW },
    );
    // verbatim: dateTime() is the dialect's own "now" (strftime on sqlite), not the live CURRENT_TIMESTAMP
    expect(source).to.include("table.dateTime('Seen').modify().notNull().default().raw(RawQuery.create('CURRENT_TIMESTAMP'));");
    expect(source).to.include("table.bigint('Counter').modify().notNull().default().raw(RawQuery.create('nextval(\\'posts_counter_seq\\'::regclass)'));");
    expect(source).to.include("table.string('Title', 100).modify();");
  });

  it('escapes line terminators and quotes in names, so a commented-out step stays a comment', () => {
    const table = "we'ird\ntable";
    const column = `na${String.fromCharCode(0x2028)}me`;
    const { source } = generateMigration(
      [{ kind: 'dropColumn', table, detail: { column }, destructive: true, reason: `${table}.${column} was removed from the models since --base` }],
      { name: 'Odd', connection: 'default', allowDestructive: false, now: NOW },
    );
    const lines = source.split('\n');
    const up = lines.indexOf('  public async up(_connection: OrmDriver): Promise<void> {');
    expect(lines.slice(up + 1, up + 6)).to.deep.equal([
      "    // DESTRUCTIVE: we'ird table.na me was removed from the models since --base (pass --allow-destructive to run it)",
      "    // await connection.schema().alterTable('we\\'ird\\ntable', (table) => {",
      "    //   table.dropColumn('na\\u2028me');",
      '    // });',
      '  }',
    ]);
  });

  it('creates a referenced table before the table that points at it', () => {
    const table = (name: string, references?: string): TargetTable => ({
      name,
      exhaustive: false,
      models: [],
      indexes: [],
      columns: [{ name: 'Id', primary: true, nullable: false, sql: { family: 'integer', inferred: true } }],
      foreignKeys: references ? [{ column: 'CompanyId', table: references, references: 'Id' }] : [],
    });
    const steps = planMigration([
      { kind: 'createTable', table: 'users', detail: table('users', 'companies'), destructive: false },
      { kind: 'createTable', table: 'companies', detail: table('companies'), destructive: false },
    ]);
    expect(steps.map((s) => s.step.table)).to.deep.equal(['companies', 'users']);
  });

  it('refuses a name the migration runner cannot read back', () => {
    expect(() => generateMigration([], { name: 'Bad_Name', connection: 'default', allowDestructive: false, now: NOW })).to.throw('Invalid migration name "Bad_Name": a letter followed by letters or digits');
  });

  it('treats every change but an unmanaged column as actionable', () => {
    expect(changes.filter(isActionable).map((c) => c.kind)).to.deep.equal(['dropColumn', 'addColumn', 'createTable']);
  });
});
