import { createGenerator } from 'ts-json-schema-generator';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function generate() {
  const config = { path: resolve(root, 'src/types.ts'), tsconfig: resolve(root, 'tsconfig.build.json'), additionalProperties: true, skipTypeCheck: true, expose: 'all', jsDoc: 'none' };
  const definitions = {};
  for (const type of ['Manifest', 'ManifestFragment']) {
    Object.assign(definitions, createGenerator({ ...config, type }).createSchema(type).definitions);
  }
  return { $schema: 'http://json-schema.org/draft-07/schema#', $id: 'https://spinajs.dev/schemas/manifest-v1.json', definitions };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const schema = generate();
  writeFileSync(resolve(root, 'src/schema.json'), JSON.stringify(schema, null, 2) + '\n');
  writeFileSync(resolve(root, 'src/schema.ts'), `// Generated by scripts/generate-schema.mjs (npm run schema). Do not edit.\nexport const manifestSchema: Record<string, any> = ${JSON.stringify(schema, null, 2)};\n`);
}
