import 'mocha';
import { expect } from 'chai';
import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { generateClient, generateClientFiles, GENERATOR_TARGETS, type GeneratorTarget } from '@spinajs/client';
import { hashManifest, readManifest } from '@spinajs/manifest';
import { Configuration, FrameworkConfiguration } from '@spinajs/configuration';
import { DI } from '@spinajs/di';
import '@spinajs/log';
import { Cli } from '../src/index.js';
import { diagnosticErrors, diagnosticLines, outputPaths, parseList, toFilesOptions, unavailableFlag, type GenerateClientFlags } from '../src/generateClientFlags.js';

const manifestPath = resolve(process.cwd(), '../compiler/test/fixtures/app-basic/app.manifest.json');

class GenerateConf extends FrameworkConfiguration {
  protected onLoad() {
    return {
      logger: {
        targets: [{ name: 'Empty', type: 'BlackHoleTarget', layout: '${message}' }],
        rules: [{ name: '*', level: 'trace', target: 'Empty' }],
      },
      system: { dirs: { cli: [resolve(process.cwd(), 'src/cli')] } },
    };
  }
}

describe('generate:client', function () {
  this.timeout(60000);

  let dir: string;

  beforeEach(async () => {
    dir = await mkdtemp(join(tmpdir(), 'client-'));
    DI.clearCache();
    DI.register(GenerateConf).as(Configuration);
    await DI.resolve(Configuration);
  });

  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  async function run(...args: string[]): Promise<void> {
    DI.register(() => ['node', 'script.js', 'generate:client', '--manifest', manifestPath, ...args]).as('__cli_argv_provider__');
    await DI.resolve(Cli);
  }

  async function rejection(...args: string[]): Promise<string> {
    try {
      await run(...args);
    } catch (err) {
      return (err as Error).message;
    }
    return '';
  }

  it('writes a typed client for the manifest', async () => {
    const out = join(dir, 'nested', 'client.ts');
    await run('--out', out);

    const source = await readFile(out, 'utf8');
    expect(source.startsWith('/* Generated by @spinajs/client')).to.equal(true);
    expect(source).to.include('export function createAppClient');
    expect(source).to.include("list: { method: 'get', path: '/users/list', args: [{ in: 'query', name: 'query', shape: 'json' }] },");
    expect(source).to.include('export const chatContract');
  });

  it('omits socket contracts with --no-socket and honours --module', async () => {
    const out = join(dir, 'client.ts');
    await run('--out', out, '--no-socket', '--module', './runtime.js');

    const source = await readFile(out, 'utf8');
    expect(source).to.include("from './runtime.js';");
    expect(source).to.not.include('chatContract');
  });

  it('writes the same client.ts as generateClient for the 4.0 invocation', async () => {
    const out = join(dir, 'client.ts');
    await run('--out', out);
    expect(await readFile(out, 'utf8')).to.equal(await generateClient({ manifest: await readManifest(manifestPath) }));
  });

  for (const name of ['client.mts', 'api']) {
    it(`writes the client to --out verbatim for ${name}`, async () => {
      const out = join(dir, name);
      await run('--out', out);
      expect(await readFile(out, 'utf8')).to.equal(await generateClient({ manifest: await readManifest(manifestPath) }));
      expect(await readdir(dir)).to.deep.equal([name]);
    });
  }

  it('writes .mts files that import each other as .mjs when --out ends in .mts', async () => {
    const out = join(dir, 'client.mts');
    await run('--out', out, '--zod');
    expect((await readdir(dir)).sort()).to.deep.equal(['client.mts', 'client.zod.mts']);
    expect(await readFile(join(dir, 'client.zod.mts'), 'utf8')).to.contain("from './client.mjs'");
  });

  it('writes extensionless sibling imports with --import-extension none', async () => {
    const out = join(dir, 'client.ts');
    await run('--out', out, '--zod', '--import-extension', 'none');
    expect(await readFile(join(dir, 'client.zod.ts'), 'utf8')).to.contain("from './client'");
  });

  // Every target has landed, so a refusal test marks its target unavailable in the table the command reads.
  async function withUnavailable<T>(target: GeneratorTarget, body: () => Promise<T>): Promise<T> {
    const entry = GENERATOR_TARGETS[target] as { available: boolean };
    const available = entry.available;
    entry.available = false;
    try {
      return await body();
    } finally {
      entry.available = available;
    }
  }

  describe('flag refusal', () => {
    const cases: [string[], GeneratorTarget][] = [
      [['--zod'], 'zod'],
      [['--models'], 'models'],
      // an available target beside an unavailable one writes nothing either
      [['--hooks', 'swr', '--socket-hooks', '--zod'], 'zod'],
      [['--next', '--models'], 'models'],
      [['--mocks'], 'mocks'],
      [['--mocks', '--msw'], 'mocks'],
    ];
    for (const [args, target] of cases) {
      it(`refuses ${args.join(' ')} naming --${target}`, async () => {
        const out = join(dir, 'client.ts');
        expect(await withUnavailable(target, () => rejection('--out', out, ...args))).to.equal(`--${target} is not available in this version`);
        expect(await readFile(out, 'utf8').catch(() => 'absent')).to.equal('absent');
      });
    }

    it('rejects an unknown hooks value with the allowed list', async () => {
      expect(await rejection('--out', join(dir, 'client.ts'), '--hooks', 'vue')).to.include('use react-query or swr');
    });

    it('rejects a hooks value that names another target, with the allowed list', async () => {
      for (const value of ['server', 'zod']) {
        expect(await rejection('--out', join(dir, 'client.ts'), '--hooks', value)).to.equal("--hooks: unknown value '" + value + "'; use react-query or swr");
      }
    });

    it('rejects a hooks target listed twice', async () => {
      expect(await rejection('--out', join(dir, 'client.ts'), '--hooks', 'swr,swr')).to.include('listed twice');
    });

    it('rejects a qualifier whose flag is missing', async () => {
      expect(await rejection('--out', join(dir, 'client.ts'), '--zod-mini')).to.equal('--zod-mini needs --zod');
      expect(await rejection('--out', join(dir, 'client.ts'), '--msw')).to.equal('--msw needs --mocks');
      expect(await rejection('--out', join(dir, 'client.ts'), '--socket-hooks')).to.equal('--socket-hooks needs --hooks');
    });

    it('writes an available target', async () => {
      const out = join(dir, 'client.ts');
      await run('--out', out, '--zod');
      expect(await readFile(out, 'utf8')).to.include('export const manifestHash');
    });
  });

  describe('flag parsing', () => {
    const base: GenerateClientFlags = { manifest: 'm.json', out: 'o.ts', socket: true };

    it('splits a comma list', () => {
      expect(parseList('react-query, swr,')).to.deep.equal(['react-query', 'swr']);
    });

    it('maps every flag to its generateClientFiles option', () => {
      const options = toFilesOptions({
        ...base,
        module: './rt.js',
        socket: false,
        hooks: ['swr'],
        zod: true,
        zodMini: true,
        zodReplies: true,
        zodUnsupported: 'error',
        models: true,
        socketHooks: true,
        keyPrefix: 'app',
        server: true,
        next: true,
        mocks: true,
        msw: true,
        importExtension: 'none',
      });
      expect(options).to.deep.equal({
        moduleName: './rt.js',
        includeSocket: false,
        hooks: ['swr'],
        zod: { mini: true, replies: true, unsupported: 'error' },
        models: true,
        socketHooks: true,
        keyPrefix: 'app',
        server: true,
        next: true,
        mocks: true,
        msw: true,
        importExtension: 'none',
      });
    });

    it('leaves zod off without --zod, and on with defaults for a bare --zod', () => {
      expect(toFilesOptions(base).zod).to.equal(undefined);
      expect(toFilesOptions({ ...base, zod: true }).zod).to.deep.equal({});
    });

    it('writes the main file to --out and names companions from its basename', () => {
      const files = [
        { path: 'x.ts', environment: 'server-safe' as const, contents: 'a' },
        { path: 'x.zod.ts', environment: 'server-safe' as const, contents: 'b' },
      ];
      expect(outputPaths(join('d', 'x.mts'), files).map((f) => f.path)).to.deep.equal([join('d', 'x.mts'), join('d', 'x.zod.ts')]);
      expect(outputPaths(join('d', 'x'), files).map((f) => f.path)).to.deep.equal([join('d', 'x'), join('d', 'x.zod.ts')]);
    });

    it('treats a target missing from the installed table as unavailable', () => {
      const older = Object.fromEntries(Object.entries(GENERATOR_TARGETS).filter(([target]) => target !== 'mocks'));
      expect(unavailableFlag({ ...base, mocks: true }, older as unknown as typeof GENERATOR_TARGETS)).to.equal('--mocks');
      expect(unavailableFlag({ ...base, hooks: ['swr'] }, { ...older, swr: { available: true } } as unknown as typeof GENERATOR_TARGETS)).to.equal(undefined);
    });

    it('names the flag as typed, and reports --next for its implied server target', () => {
      const table = { ...GENERATOR_TARGETS, server: { available: false }, next: { available: true } };
      expect(unavailableFlag({ ...base, next: true }, table)).to.equal('--next');
      expect(unavailableFlag({ ...base, hooks: ['swr'] }, { ...table, swr: { available: true } })).to.equal(undefined);
    });
  });

  describe('--check', () => {
    let stderr = '';
    let realWrite: typeof process.stderr.write;

    beforeEach(() => {
      stderr = '';
      realWrite = process.stderr.write.bind(process.stderr);
      process.stderr.write = ((chunk: string | Uint8Array) => {
        stderr += String(chunk);
        return true;
      });
      process.exitCode = undefined;
    });

    afterEach(() => {
      process.stderr.write = realWrite;
      process.exitCode = undefined;
    });

    // The Cli singleton runs once per DI cache, so the file under check is written directly.
    async function writeCurrent(): Promise<string> {
      const out = join(dir, 'client.ts');
      await writeFile(out, await generateClient({ manifest: await readManifest(manifestPath) }));
      return out;
    }

    it('exits 0 and reports nothing when the file is current', async () => {
      const out = await writeCurrent();
      await run('--out', out, '--check');
      expect(process.exitCode).to.equal(undefined);
      expect(stderr).to.equal('');
    });

    it('exits 1 naming a changed file, and leaves it alone', async () => {
      const out = await writeCurrent();
      const edited = `${await readFile(out, 'utf8')}x`;
      await writeFile(out, edited);
      await run('--out', out, '--check');
      expect(process.exitCode).to.equal(1);
      expect(stderr).to.include(`${out} (differs)`);
      expect(await readFile(out, 'utf8')).to.equal(edited);
    });

    it('exits 1 naming a missing file, without creating it', async () => {
      const out = join(dir, 'nested', 'client.ts');
      await run('--out', out, '--check');
      expect(process.exitCode).to.equal(1);
      expect(stderr).to.include(`${out} (missing)`);
      expect(await readFile(out, 'utf8').catch(() => 'absent')).to.equal('absent');
    });

    it('checks the --out path itself, whatever its extension', async () => {
      const out = join(dir, 'client.mts');
      await writeFile(out, await generateClient({ manifest: await readManifest(manifestPath) }));
      await run('--out', out, '--check');
      expect(process.exitCode).to.equal(undefined);
      expect(stderr).to.equal('');
    });

    it('reports a missing --out without an extension under that name', async () => {
      const out = join(dir, 'api');
      await run('--out', out, '--check');
      expect(process.exitCode).to.equal(1);
      expect(stderr).to.include(`${out} (missing)`);
    });

    it('ignores the line-ending conversion of a checkout', async () => {
      const out = await writeCurrent();
      await writeFile(out, (await readFile(out, 'utf8')).replace(/\n/g, '\r\n'));
      await run('--out', out, '--check');
      expect(process.exitCode).to.equal(undefined);
    });
  });

  describe('generator diagnostics', () => {
    const ZOD002 = 'ZOD002 spinajs/app-basic/CreateUserDto#/properties/email/format: ';
    const SUMMARY = /^\d+ generator diagnostic\(s\) are errors \(--zod-unsupported error\); no file was written or checked$/m;
    let stderr = '';
    let realWrite: typeof process.stderr.write;

    beforeEach(() => {
      stderr = '';
      realWrite = process.stderr.write.bind(process.stderr);
      process.stderr.write = ((chunk: string | Uint8Array) => {
        stderr += String(chunk);
        return true;
      });
      process.exitCode = undefined;
    });

    afterEach(() => {
      process.stderr.write = realWrite;
      process.exitCode = undefined;
    });

    const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);

    /** app-basic with a format Ajv does not know on CreateUserDto.email: the zod emitter reports ZOD002 there. */
    async function manifestWithUnknownFormat(): Promise<string> {
      const manifest = await readManifest(manifestPath);
      const schema: unknown = manifest.schemas['spinajs/app-basic/CreateUserDto'];
      const properties = isRecord(schema) ? schema.properties : undefined;
      const email = isRecord(properties) ? properties.email : undefined;
      if (!isRecord(email)) throw new Error('app-basic has no CreateUserDto.email schema');
      email.format = 'x-unknown';
      const file = join(dir, 'app.manifest.json');
      await writeFile(file, JSON.stringify({ ...manifest, hash: hashManifest(manifest) }));
      return file;
    }

    it('prints a warning to stderr, writes the files and leaves the exit code alone', async () => {
      const manifest = await manifestWithUnknownFormat();
      await run('--manifest', manifest, '--out', join(dir, 'client.ts'), '--zod');
      expect(stderr).to.include(`client.zod.ts: warning ${ZOD002}`);
      expect(stderr).to.not.match(SUMMARY);
      expect(process.exitCode).to.equal(undefined);
      expect((await readdir(dir)).sort()).to.deep.equal(['app.manifest.json', 'client.ts', 'client.zod.ts']);
    });

    it('prints the error and a summary line, writes nothing and exits 1 with --zod-unsupported error', async () => {
      const manifest = await manifestWithUnknownFormat();
      await run('--manifest', manifest, '--out', join(dir, 'client.ts'), '--zod', '--zod-unsupported', 'error');
      expect(stderr).to.include(`client.zod.ts: error ${ZOD002}`);
      expect(stderr).to.match(SUMMARY);
      expect(process.exitCode).to.equal(1);
      expect(await readdir(dir)).to.deep.equal(['app.manifest.json']);
    });

    it('exits 1 the same way under --check, before any file is compared', async () => {
      const manifest = await manifestWithUnknownFormat();
      await run('--manifest', manifest, '--out', join(dir, 'client.ts'), '--zod', '--zod-unsupported', 'error', '--check');
      expect(stderr).to.match(SUMMARY);
      expect(stderr).to.not.include('out of date');
      expect(process.exitCode).to.equal(1);
      expect(await readdir(dir)).to.deep.equal(['app.manifest.json']);
    });

    it('prints a warning under --check, writes nothing to stdout and leaves the exit code to the comparison', async () => {
      const manifest = await manifestWithUnknownFormat();
      const out = join(dir, 'client.ts');
      const current = await generateClientFiles({ manifest: await readManifest(manifest), zod: true });
      for (const file of outputPaths(out, current)) await writeFile(file.path, file.contents);
      let stdout = '';
      const realStdout = process.stdout.write.bind(process.stdout);
      process.stdout.write = ((chunk: string | Uint8Array) => {
        stdout += String(chunk);
        return true;
      });
      try {
        await run('--manifest', manifest, '--out', out, '--zod', '--check');
      } finally {
        process.stdout.write = realStdout;
      }
      expect(stderr).to.include(`client.zod.ts: warning ${ZOD002}`);
      expect(stderr).to.not.match(SUMMARY);
      expect(stderr).to.not.include('out of date');
      expect(stdout).to.not.include('ZOD002');
      expect(process.exitCode).to.equal(undefined);
    });

    it('prints no diagnostic line and keeps exit code 0 for a manifest that has none', async () => {
      await run('--out', join(dir, 'client.ts'), '--zod', '--zod-unsupported', 'error');
      expect(stderr).to.not.include('client.zod.ts: ');
      expect(process.exitCode).to.equal(undefined);
      expect((await readdir(dir)).sort()).to.deep.equal(['client.ts', 'client.zod.ts']);
    });
  });
});

describe('generate:client diagnostics', () => {
  const files = [
    { path: 'client.ts', environment: 'server-safe' as const, contents: '' },
    {
      path: 'client.zod.ts',
      environment: 'server-safe' as const,
      contents: '',
      diagnostics: [
        { code: 'ZOD002' as const, severity: 'warning' as const, schema: 'app/UserDto', pointer: '/properties/email', message: 'format x-unknown is not known to Ajv; the server accepts every value' },
        { code: 'ZOD003' as const, severity: 'error' as const, schema: 'app/UserDto', pointer: '/instanceof', message: 'instanceof is dropped' },
      ],
    },
  ];

  it('prints one line per diagnostic with file, severity, code, schema and pointer', () => {
    expect(diagnosticLines(files)).to.deep.equal([
      'client.zod.ts: warning ZOD002 app/UserDto#/properties/email: format x-unknown is not known to Ajv; the server accepts every value',
      'client.zod.ts: error ZOD003 app/UserDto#/instanceof: instanceof is dropped',
    ]);
  });

  it('counts the errors only', () => {
    expect(diagnosticErrors(files)).to.equal(1);
    expect(diagnosticErrors([files[0]])).to.equal(0);
  });
});
