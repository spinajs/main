import { publishedManifest } from '@spinajs/manifest';
import type { Manifest } from '@spinajs/manifest';
import { emitDtoTypes } from './generate/dto-types.js';
import { controllerBase, controllerKey, routeSignature } from './generate/routes.js';
import { emitContract } from './generate/socket.js';
import { TypeContext } from './generate/ts-type.js';

export interface GenerateClientOptions {
  manifest: Manifest;
  /** Import path of the runtime, default `@spinajs/client/runtime`. */
  moduleName?: string;
  /** Default: true when the manifest has socket controllers. */
  includeSocket?: boolean;
}

/** Generates TypeScript source for a typed HTTP client (and socket contracts) from an application manifest. */
export async function generateClient(options: GenerateClientOptions): Promise<string> {
  const manifest = publishedManifest(options.manifest);
  const moduleName = options.moduleName ?? '@spinajs/client/runtime';
  const includeSocket = options.includeSocket ?? manifest.socketControllers.length > 0;
  const ctx = new TypeContext(manifest);

  const controllers = [...manifest.controllers].filter((c) => c.routes.length > 0).sort((a, b) => a.className.localeCompare(b.className) || a.id.localeCompare(b.id));
  const interfaces: string[] = [];
  const definitions: string[] = [];
  for (const controller of controllers) {
    const signatures = controller.routes.map((r) => routeSignature(controller, r, ctx));
    const methods = signatures.map((s) => `  ${s.name}(${s.args.join(', ')}): Promise<${s.returns}>;`);
    interfaces.push(`export interface ${controllerBase(controller)}Client {\n${methods.join('\n')}\n}`);
    definitions.push(`  ${controllerKey(controller)}: {\n${signatures.map((s) => `    ${s.name}: ${s.definition},`).join('\n')}\n  },`);
  }
  const appClient = `export interface AppClient {\n${controllers.map((c) => `  ${controllerKey(c)}: ${controllerBase(c)}Client;`).join('\n')}\n}`;
  const contracts = includeSocket
    ? [...manifest.socketControllers].sort((a, b) => a.prefix.localeCompare(b.prefix) || a.id.localeCompare(b.id)).map((c) => emitContract(c, ctx))
    : [];
  const dtoTypes = await emitDtoTypes(ctx);

  const lines = [
    `/* Generated by @spinajs/client from app.manifest.json (hash ${manifest.hash}). Do not edit. */`,
    `import { createClient, type ClientDefinition, type ClientOptions } from '${moduleName}';`,
    ...(includeSocket ? [`import { defineContract } from '@spinajs/http-socket-common';`] : []),
    '',
    ...(dtoTypes ? [dtoTypes, ''] : []),
    ...interfaces.flatMap((i) => [i, '']),
    appClient,
    '',
    `const definition: ClientDefinition = {\n${definitions.join('\n')}\n};`,
    '',
    'export function createAppClient(options: ClientOptions): AppClient {',
    '  return createClient<AppClient>(definition, options);',
    '}',
    ...contracts.flatMap((c) => ['', c]),
  ];
  return `${lines.join('\n')}\n`;
}
