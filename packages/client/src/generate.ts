import type { Manifest } from '@spinajs/manifest';
import { emitDtoTypes } from './generate/dto-types.js';
import { buildClientModel, type ClientModel } from './generate/model.js';
import { parameterList } from './generate/routes.js';
import { emitContract } from './generate/socket.js';
import { literal } from './generate/ts-type.js';

export interface GenerateClientOptions {
  manifest: Manifest;
  /** Import path of the runtime, default `@spinajs/client/runtime`. */
  moduleName?: string;
  /** Default: true when the manifest has socket controllers. */
  includeSocket?: boolean;
}

export interface EmitClientOptions {
  moduleName?: string;
  /** Exports `manifestHash`, which companion files check at compile time. */
  manifestHash?: boolean;
}

export async function emitClient(model: ClientModel, options: EmitClientOptions = {}): Promise<string> {
  const { ctx } = model;
  const moduleName = options.moduleName ?? '@spinajs/client/runtime';

  const interfaces = model.controllers.map((c) => `export interface ${c.base}Client {\n${c.routes.map((r) => `  ${r.name}(${parameterList(r.args).join(', ')}): Promise<${r.returns}>;`).join('\n')}\n}`);
  const definitions = model.controllers.map((c) => `  ${c.key}: {\n${c.routes.map((r) => `    ${r.name}: ${r.definition},`).join('\n')}\n  },`);
  const appClient = `export interface AppClient {\n${model.controllers.map((c) => `  ${c.key}: ${c.base}Client;`).join('\n')}\n}`;
  const contracts = model.sockets.map((c) => emitContract(c, ctx));
  const dtoTypes = await emitDtoTypes(ctx);

  const lines = [
    `/* Generated by @spinajs/client from app.manifest.json (hash ${model.manifestHash}). Do not edit. */`,
    `import { createClient, type ClientDefinition, type ClientOptions } from '${moduleName}';`,
    ...(model.includeSocket ? [`import { defineContract } from '@spinajs/http-socket-common';`] : []),
    '',
    ...(options.manifestHash ? [`export const manifestHash = ${literal(model.manifestHash)};`, ''] : []),
    ...(dtoTypes ? [dtoTypes, ''] : []),
    ...interfaces.flatMap((i) => [i, '']),
    appClient,
    '',
    `const definition: ClientDefinition = {\n${definitions.join('\n')}\n};`,
    '',
    'export function createAppClient(options: ClientOptions): AppClient {',
    '  return createClient<AppClient>(definition, options);',
    '}',
    ...contracts.flatMap((c) => ['', c]),
  ];
  return `${lines.join('\n')}\n`;
}

/** Generates TypeScript source for a typed HTTP client (and socket contracts) from an application manifest. */
export async function generateClient(options: GenerateClientOptions): Promise<string> {
  return emitClient(buildClientModel(options.manifest, { includeSocket: options.includeSocket }), { moduleName: options.moduleName });
}
