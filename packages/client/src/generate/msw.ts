import type { ClientModel } from './model.js';
import { clientPath } from './path.js';
import { literal, propertyKey } from './ts-type.js';

export interface MswEmitResult {
  contents: string;
}

// MSW reads `:name` as \w+ and has no `{...}` groups or named wildcards: `*` is its only wildcard, reported as params['0'], params['1'], ...
const MSW_NAME = /^[A-Za-z_]\w*$/;
const MSW_SPECIAL = /[:*]/;

interface Parsed {
  variants: string[];
  next: number;
}

/** Reads a client path template (`{name}`, `{*name}`, `[...]`, `\` escapes) into every path MSW needs to match it. */
function variantsOf(template: string, start: number, nested: boolean): Parsed {
  let variants = [''];
  let i = start;
  const append = (text: string) => {
    variants = variants.map((v) => v + text);
  };
  while (i < template.length) {
    const char = template[i];
    if (char === ']') {
      if (nested) return { variants, next: i + 1 };
      throw new Error(`unbalanced ']' at index ${i}`);
    }
    if (char === '[') {
      const group = variantsOf(template, i + 1, true);
      variants = variants.flatMap((v) => [v, ...group.variants.map((g) => v + g)]);
      i = group.next;
    } else if (char === '{') {
      const end = template.indexOf('}', i);
      const name = template.slice(i + 1, end);
      if (name.startsWith('*')) append('*');
      else if (MSW_NAME.test(name)) append(`:${name}`);
      else throw new Error(`parameter name '${name}' cannot be written as an MSW path parameter; use letters, digits and underscores`);
      i = end + 1;
    } else {
      const literalChar = char === '\\' ? template[++i] : char;
      append(MSW_SPECIAL.test(literalChar) ? `\\${literalChar}` : literalChar);
      i++;
    }
  }
  return { variants, next: i };
}

/** The MSW paths that together match an Express 5 route path: an optional group gives one path with and one without it. */
export function mswPaths(expressPath: string): string[] {
  const { variants } = variantsOf(clientPath(expressPath).template, 0, false);
  return [...new Set(variants.map((v) => (v === '' ? '/' : v)))];
}

function paramsType(expressPath: string): string {
  let wildcards = 0;
  const names = clientPath(expressPath).placeholders.map((p) => literal(p.splat ? String(wildcards++) : p.name));
  return `PathParams<${names.length > 0 ? names.join(' | ') : 'never'}>`;
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const member = (name: string, optional: boolean): string => `${optional ? '?' : ''}${IDENTIFIER.test(name) ? '.' + name : (optional ? '.' : '') + '[' + literal(name) + ']'}`;

/**
 * Prints `client.msw.ts`: one MSW handler per route, answering with the mock data of `client.mocks.ts`.
 * `msw` is imported here and nowhere else.
 */
export function emitMsw(model: ClientModel, clientModule = './client.js', mocksModule = './client.mocks.js'): MswEmitResult {
  const overrides: string[] = [];
  const handlers: string[] = [];
  for (const controller of model.controllers) {
    const members: string[] = [];
    for (const route of controller.routes) {
      const ids = `${literal(controller.key)}, ${literal(route.name)}`;
      const params = paramsType(route.fullPath);
      const resolver = `HttpResponseResolver<${params}, DefaultBodyType, Reply<${ids}>>`;
      members.push(`    ${propertyKey(route.name)}?: ${resolver};`);
      const fallback = route.returns === 'void' ? '() => new HttpResponse(null, { status: 204 })' : `async () => HttpResponse.json((await mocked(${ids})) as Reply<${ids}>)`;
      const access = `overrides${member(controller.key, false)}${member(route.name, true)} ?? (${fallback})`;
      for (const path of mswPaths(route.fullPath)) {
        handlers.push(`    http.${route.method}<${params}, DefaultBodyType, Reply<${ids}>>(base + ${literal(path)}, ${access}),`);
      }
    }
    overrides.push(`  ${propertyKey(controller.key)}?: {\n${members.join('\n')}\n  };`);
  }
  const lines = [
    `/* Generated by @spinajs/client (msw) from app.manifest.json (hash ${model.manifestHash}). Do not edit. */`,
    `import { http, HttpResponse, type DefaultBodyType, type HttpResponseResolver, type JsonBodyType, type PathParams, type RequestHandler } from 'msw';`,
    `import type { AppClient, manifestHash } from '${clientModule}';`,
    `import { createMockAppClient } from '${mocksModule}';`,
    '',
    `const _hash: typeof manifestHash = ${literal(model.manifestHash)};`,
    'void _hash;',
    '',
    '// The body type of a route\'s reply; a route with no reply answers 204.',
    'type Reply<C extends keyof AppClient, H extends keyof AppClient[C]> = AppClient[C][H] extends (...args: never[]) => Promise<infer R>',
    '  ? [R] extends [void]',
    '    ? undefined',
    '    : R extends JsonBodyType',
    '      ? R',
    '      : JsonBodyType',
    '  : never;',
    '',
    overrides.length > 0 ? `export interface AppHandlerOverrides {\n${overrides.join('\n')}\n}` : 'export type AppHandlerOverrides = Record<string, never>;',
    '',
    `const fake = createMockAppClient({}, { fallback: 'mock' }) as unknown as Record<string, Record<string, () => Promise<unknown>>>;`,
    '',
    'function mocked(controller: string, handler: string): Promise<unknown> {',
    '  return fake[controller][handler]();',
    '}',
    '',
    'export function createAppHandlers(baseUrl: string, overrides: AppHandlerOverrides = {}): RequestHandler[] {',
    "  const base = baseUrl.replace(/\\/+$/, '');",
    handlers.length > 0 ? `  return [\n${handlers.join('\n')}\n  ];` : '  void overrides;\n  void base;\n  return [];',
    '}',
  ];
  return { contents: `${lines.join('\n')}\n` };
}
