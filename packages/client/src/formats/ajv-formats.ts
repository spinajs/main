function isLeapYear(year: number): boolean {
  return year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
}

const DATE = /^(\d\d\d\d)-(\d\d)-(\d\d)$/;
const DAYS = [0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

export function isDate(str: string): boolean {
  const matches = DATE.exec(str);
  if (!matches) return false;
  const year = +matches[1];
  const month = +matches[2];
  const day = +matches[3];
  return month >= 1 && month <= 12 && day >= 1 && day <= (month === 2 && isLeapYear(year) ? 29 : DAYS[month]);
}

const TIME = /^(\d\d):(\d\d):(\d\d)(\.\d+)?(z|[+-]\d\d(?::?\d\d)?)?$/i;

function time(str: string, withTimeZone: boolean): boolean {
  const matches = TIME.exec(str);
  if (!matches) return false;
  const hour = +matches[1];
  const minute = +matches[2];
  const second = +matches[3];
  // An absent zone is undefined, never '': ajv-formats 2.1.1 accepts a date-time without one.
  const timeZone = matches[5] as string | undefined;
  return ((hour <= 23 && minute <= 59 && second <= 59) || (hour === 23 && minute === 59 && second === 60)) && (!withTimeZone || timeZone !== '');
}

export function isTime(str: string): boolean {
  return time(str, false);
}

const DATE_TIME_SEPARATOR = /t|\s/i;

export function isDateTime(str: string): boolean {
  const dateTime = str.split(DATE_TIME_SEPARATOR);
  return dateTime.length === 2 && isDate(dateTime[0]) && time(dateTime[1], true);
}

export function isDuration(str: string): boolean {
  return DURATION.test(str);
}

const NOT_URI_FRAGMENT = /\/|:/;
