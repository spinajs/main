const Z_ANCHOR = /[^\\]\\Z/;

export function isRegex(str: string): boolean {
  if (Z_ANCHOR.test(str)) return false;
  try {
    new RegExp(str);
    return true;
  } catch {
    return false;
  }
}

export function isUuid(str: string): boolean {
  return UUID.test(str);
}

