import 'mocha';
import { expect } from 'chai';
import { Configuration, FrameworkConfiguration } from '@spinajs/configuration';
import { Bootstrapper, DI } from '@spinajs/di';
import type { ModelEntry } from '@spinajs/manifest';
import { buildTargetSchema, diffSchema, introspectSchema, Orm, planMigration, renderSql, runStep, type OrmDriver, type SchemaChange } from '@spinajs/orm';
import '@spinajs/log';
import '@spinajs/orm-sqlite';
import '../src/index.js';
import { col, id, manifestOf, model } from './migrate-diff.fixture.js';

class SqlConf extends FrameworkConfiguration {
  public async resolve(): Promise<void> {
    await super.resolve();
    this.Config.logger = { targets: [{ name: 'Empty', type: 'BlackHoleTarget' }], rules: [{ name: '*', level: 'trace', target: 'Empty' }] };
    this.Config.db = {
      StrictTableCheck: false,
      Connections: [
        { Driver: 'orm-driver-pglite', Filename: ':memory:', Name: 'pglite' },
        { Driver: 'orm-driver-sqlite', Filename: ':memory:', Name: 'sqlite' },
      ],
    };
  }
}

for (const connection of ['pglite', 'sqlite'] as const) {
  describe(`renderSql and runStep on ${connection}`, function () {
    this.timeout(60_000);
    let driver: OrmDriver;

    const changesFor = async (models: ModelEntry[]): Promise<SchemaChange[]> => {
      const target = buildTargetSchema(manifestOf(models), 'default');
      const live = await introspectSchema(driver, target.map((t) => t.name));
      return diffSchema(target, live.columns, live.extras, { dialect: live.dialect });
    };

    before(async () => {
      DI.register(SqlConf).as(Configuration);
      for (const b of await DI.resolve(Array.ofType(Bootstrapper))) await b.bootstrap();
      const found = (await DI.resolve(Orm)).Connections.get(connection);
      if (!found) throw new Error(`no ${connection} connection`);
      driver = found;
    });

    after(async () => {
      await (await DI.resolve(Orm)).dispose();
      DI.clearCache();
    });

    const items = [model('Item', 'rs_items', [id(), col('Name', { family: 'text', length: 80 })])];

    it('compiles the DDL for the dialect without creating anything', async () => {
      const sql = (await renderSql(await changesFor(items), driver, { allowDestructive: false })).join('\n');
      expect(sql).to.match(/CREATE TABLE[^\n]*rs_items/);
      expect(sql).to.include(connection === 'pglite' ? 'GENERATED BY DEFAULT AS IDENTITY' : 'AUTOINCREMENT');
      expect((await introspectSchema(driver, ['rs_items'])).columns.has('rs_items')).to.equal(false);
    });

    it('runs the same steps for real', async () => {
      for (const planned of planMigration(await changesFor(items))) await runStep(driver, planned.step);
      expect(await changesFor(items)).to.deep.equal([]);
    });

    it('leaves DESTRUCTIVE steps out unless allowed, and marks a step it cannot compile offline', async () => {
      await driver.schema().createTable('rs_legacy', (table) => {
        table.int('Id').primaryKey().autoIncrement();
        table.text('Old');
        table.text('Note');
      });
      const changes = await changesFor([model('Legacy', 'rs_legacy', [id(), col('Note', { family: 'text' })], { exhaustive: true })]);
      const without = (await renderSql(changes, driver, { allowDestructive: false })).join('\n');
      const withDrops = (await renderSql(changes, driver, { allowDestructive: true })).join('\n');
      expect(without).to.not.match(/DROP COLUMN/i);
      expect(without).to.include('-- DESTRUCTIVE alterTable rs_legacy: rs_legacy is exhaustive and no model declares Old (left out; pass --allow-destructive)');
      expect(withDrops).to.match(/DROP COLUMN/i);
      expect(withDrops).to.not.include('-- DESTRUCTIVE');
      // prefix only: the rest of the sqlite line is the driver's own error (the recorder answered [] for sqlite_master, so the rebuild found "no such table")
      expect(without).to.include(connection === 'pglite' ? 'SET NOT NULL' : '-- alterTable rs_legacy is not compiled offline: ');
    });

    it('records CREATE INDEX without the semicolon its compiler ends it with', async () => {
      const indexed = [model('Item', 'rs_items', [id(), col('Name', { family: 'text', length: 80 })], { indexes: [{ columns: ['Name'], unique: false }] })];
      const sql = await renderSql(await changesFor(indexed), driver, { allowDestructive: false });
      expect(sql.join(' ')).to.match(/CREATE INDEX/i);
      expect(sql.filter((s) => s.endsWith(';'))).to.deep.equal([]);
    });
  });
}
