import { expect } from 'chai';
import * as fs from 'node:fs';
import * as os from 'node:os';
import { join } from 'node:path';

import { ConversionError, WARNINGS_FILE, convert, main } from '../src/index.js';
import type { ConvertResult, DbFacts } from '../src/index.js';

/** A config dir of CommonJS files (a temp dir has no package.json that makes .js an ES module). */
function configDir(files: Record<string, unknown>): string {
  const dir = fs.mkdtempSync(join(os.tmpdir(), 'authz-convert-'));
  for (const [name, value] of Object.entries(files)) fs.writeFileSync(join(dir, name), `module.exports = ${JSON.stringify(value)};\n`);
  return dir;
}

const file = (r: ConvertResult, name: string) => r.files.find((f) => f.name === name)?.content;
const load = (text: string): unknown => new Function(`return ${text.replace(/^\/\/.*$/gm, '').replace('export default', '').trim().replace(/;$/, '')};`)();

async function refusal(dirs: string[]): Promise<ConversionError> {
  try {
    await convert({ dirs });
  } catch (err) {
    expect(err).to.be.instanceOf(ConversionError);
    return err as ConversionError;
  }
  throw new Error('expected a refusal');
}

const HTTP = { http: { trustProxy: 1, cors: { origins: ['https://app'] }, cookie: { secret: 'env://S' } } };
// The 2.x defaults an app sets itself, so the package-default findings stay out of the way.
const RBAC = { session: { cookie: { hostPrefix: false } }, password: { expiration: { enabled: false }, blockAfterAttempts: 5 }, twoFactorAuth: { enabled: false }, auth: { service: 'SimpleDbAuthProvider' }, defaultRole: 'user', enableGuestAccount: false };

describe('convert', () => {
  it('writes one file per root and layer, named so the 3.0 loader reads them', async () => {
    const dir = configDir({
      'rbac.js': { ...HTTP, rbac: { ...RBAC, defaultRole: 'user', grants: { user: { Doc: { 'read:any': ['*'] } } }, email: { connection: 'mail' }, session: { cookie: { hostPrefix: false } } } },
      'twofa.local.js': { rbac: { twoFactorAuth: { enabled: false, forceUser: false } } },
    });
    const r = await convert({ dirs: [dir] });
    expect(r.files.map((f) => f.name)).to.deep.equal(['authz-generated.ts', 'users-generated.ts', 'authn-generated.ts', 'authn-generated.local.ts', WARNINGS_FILE]);
    expect(load(file(r, 'authz-generated.ts')!)).to.deep.equal({
      authz: { principals: { anonymous: { enabled: false } }, rbac: { defaultRoles: ['user'], roles: { user: { grants: ['Doc:read'] } } }, permissions: { 'Doc:read': {} } },
    });
    expect(load(file(r, 'users-generated.ts')!)).to.deep.equal({ users: { email: { connection: 'mail' } } });
    expect(load(file(r, 'authn-generated.local.ts')!)).to.deep.equal({ authn: { mfa: { policy: { force: false } } } });
    expect(file(r, 'authz-generated.ts')).to.match(/^\/\/ Generated by spinajs-authz-convert .*common files/);
    expect(r.exitCode).to.equal(0);
  });

  it('refuses an attribute list set in common and in an env file, which 2.x joined before reading', async () => {
    const dir = configDir({
      'rbac.js': { rbac: { grants: { r: { Doc: { 'read:any': ['!Secret'] } } } } },
      'rbac.prod.js': { rbac: { grants: { r: { Doc: { 'read:any': ['*'] } } } } },
    });
    const err = await refusal([dir]);
    expect(err.problems.join('\n')).to.match(/\[prod\] rbac\.grants\['r'\]\['Doc'\]\['read:any'\] is set in common and in env 'prod'/);
  });

  it('checks declared roles of an env file against the roles common grants', async () => {
    const dir = configDir({
      'rbac.js': { ...HTTP, rbac: { ...RBAC, grants: { admin: {} }, session: { cookie: { hostPrefix: false } } } },
      'roles.local.js': { rbac: { roles: [{ Name: 'admin', Description: 'Administrator' }] } },
    });
    const r = await convert({ dirs: [dir] });
    expect(load(file(r, 'authz-generated.local.ts')!)).to.deep.equal({ authz: { rbac: { roles: { admin: { description: 'Administrator', grants: [] } } } } });
    expect(r.findings.filter((x) => x.code === 'declared-without-grants')).to.deep.equal([]);
  });

  it('leaves an array key set in common and in an env file for a person', async () => {
    const dir = configDir({
      'rbac.js': { ...HTTP, rbac: { ...RBAC, defaultRole: 'user', session: { cookie: { hostPrefix: false } } } },
      'rbac.local.js': { rbac: { defaultRole: 'admin' } },
    });
    const r = await convert({ dirs: [dir] });
    expect(file(r, 'authz-generated.local.ts')).to.equal(undefined);
    expect(r.findings.find((x) => x.code === 'env-array')?.layer).to.equal('local');
    expect(r.exitCode).to.equal(2);
  });

  it('drops an array key an env file sets to the common value, and leaves an env that turns it off for a person', async () => {
    const same = configDir({
      'rbac.js': { ...HTTP, rbac: { ...RBAC, twoFactorAuth: { enabled: true }, session: { cookie: { hostPrefix: false } } } },
      'rbac.local.js': { rbac: { twoFactorAuth: { enabled: true } } },
    });
    const r = await convert({ dirs: [same] });
    expect(file(r, 'authn-generated.local.ts')).to.equal(undefined);
    expect(r.findings.filter((x) => x.code === 'env-array')).to.deep.equal([]);

    const off = configDir({
      'rbac.js': { ...HTTP, rbac: { ...RBAC, twoFactorAuth: { enabled: true }, session: { cookie: { hostPrefix: false } } } },
      'rbac.local.js': { rbac: { twoFactorAuth: { enabled: false } } },
    });
    const r2 = await convert({ dirs: [off] });
    expect(r2.findings.find((x) => x.code === 'env-array')?.message).to.match(/Env 'local' turns off what authn\.mfa\.steps holds in common/);
    expect(r2.exitCode).to.equal(2);
  });

  it('writes the 2.x default login strategy when the app left rbac.auth out', async () => {
    const dir = configDir({ 'rbac.js': { ...HTTP, rbac: { ...RBAC, auth: undefined } } });
    const r = await convert({ dirs: [dir] });
    expect((load(file(r, 'authn-generated.ts')!) as any).authn.strategies).to.deep.equal([{ name: 'local', service: 'LocalPasswordStrategy' }]);
    expect(r.findings.map((x) => x.code)).to.include('auth-default');
  });

  it('leaves an env that names another login provider for a person, since common lists the local strategy', async () => {
    const dir = configDir({
      'rbac.js': { ...HTTP, rbac: { ...RBAC, auth: undefined } },
      'rbac.prod.js': { rbac: { auth: { service: 'LdapAuthProvider' } } },
      'rbac.dev.js': { rbac: { auth: { service: 'SimpleDbAuthProvider' } } },
    });
    const r = await convert({ dirs: [dir] });
    expect(r.findings.filter((x) => x.code === 'env-array').map((x) => x.layer)).to.deep.equal(['prod']);
    expect(file(r, 'authn-generated.dev.ts')).to.equal(undefined);
  });

  it('leaves any env whose login provider differs from common for a person, whichever side names it', async () => {
    for (const [common, prod] of [
      ['SimpleDbAuthProvider', 'LdapAuthProvider'],
      ['LdapAuthProvider', 'SimpleDbAuthProvider'],
    ]) {
      const dir = configDir({ 'rbac.js': { ...HTTP, rbac: { ...RBAC, auth: { service: common } } }, 'rbac.prod.js': { rbac: { auth: { service: prod } } } });
      const r = await convert({ dirs: [dir] });
      expect(r.findings.filter((x) => x.code === 'env-array').map((x) => x.layer)).to.deep.equal(['prod']);
    }
  });

  it('writes the local strategy into an env layer when only env files hold rbac keys', async () => {
    const dir = configDir({ 'http.js': HTTP, 'rbac.local.js': { rbac: { defaultRole: 'user' } } });
    const r = await convert({ dirs: [dir] });
    expect((load(file(r, 'authn-generated.local.ts')!) as any).authn.strategies).to.deep.equal([{ name: 'local', service: 'LocalPasswordStrategy' }]);
  });

  it('asks once for the MFA encryption key, however many layers write the totp step', async () => {
    const dir = configDir({
      'rbac.js': { ...HTTP, rbac: { ...RBAC, twoFactorAuth: { enabled: true } } },
      'rbac.local.js': { rbac: { twoFactorAuth: { forceUser: true } } },
    });
    const r = await convert({ dirs: [dir] });
    expect(r.findings.filter((x) => x.code === 'mfa-key')).to.have.length(1);
  });

  it('collects the refusals of every layer before it gives up', async () => {
    const dir = configDir({
      'rbac.js': { rbac: { grants: { r: { Doc: { 'READ:any': ['*'] } } } } },
      'rbac.local.js': { rbac: { defaultRole: 5 } },
    });
    const err = await refusal([dir]);
    expect(err.problems).to.have.length(2);
  });

  it('marks roles no one holds and others extend not assignable, with DB facts', async () => {
    const dir = configDir({
      'rbac.js': {
        ...HTTP,
        rbac: { ...RBAC, defaultRole: 'user', grants: { user: {}, 'admin.users': {}, admin: { $extend: ['admin.users', 'user'] }, 'route.home': {}, sales: { $extend: ['route.home'] } }, session: { cookie: { hostPrefix: false } } },
      },
    });
    const db: DbFacts = { users: [{ id: 'a', roles: ['admin'] }], tokens: [{ id: 't', roles: ['sales'], expiresAt: '2030-01-01' }] };
    const { convertLayers, loadLayers } = await import('../src/index.js');
    const r = convertLayers(await loadLayers([dir]), { db });
    const roles = (load(file(r, 'authz-generated.ts')!) as any).authz.rbac.roles;
    expect(Object.entries(roles).filter(([, d]) => (d as any).assignable === false).map(([n]) => n)).to.deep.equal(['admin.users', 'route.home']);
    expect(r.findings.find((x) => x.code === 'assignable' && x.severity === 'info' && /written 'assignable: false'/.test(x.message))).to.not.equal(undefined);
  });

  it('writes the warnings file with a section per severity', async () => {
    const dir = configDir({ 'rbac.js': { rbac: { accountTypes: {}, password: { blockAfterAttempts: 3 } } } });
    const r = await convert({ dirs: [dir] });
    const md = file(r, WARNINGS_FILE)!;
    expect(md).to.match(/## Convert by hand \(\d+\)[\s\S]*rbac\.accountTypes[\s\S]*## Behaviour changes and actions[\s\S]*lockout-to-backoff[\s\S]*## Notes/);
    expect(r.exitCode).to.equal(2);
  });
});

describe('main', () => {
  it('writes the files, refuses to overwrite them without --force, and answers with the exit code', async () => {
    const dir = configDir({ 'rbac.js': { ...HTTP, rbac: { ...RBAC, defaultRole: 'user', session: { cookie: { hostPrefix: false } } } } });
    const out = fs.mkdtempSync(join(os.tmpdir(), 'authz-convert-out-'));
    const logs: string[] = [];
    const errors: string[] = [];
    expect(await main([dir, '--out', out], (l) => logs.push(l), (l) => errors.push(l))).to.equal(0);
    expect(fs.readdirSync(out).sort()).to.deep.equal(['authn-generated.ts', 'authz-generated.ts', WARNINGS_FILE]);
    expect(await main([dir, '--out', out], (l) => logs.push(l), (l) => errors.push(l))).to.equal(1);
    expect(errors.join('\n')).to.match(/--force was not given/);
    expect(await main([dir, '--out', out, '--force'], (l) => logs.push(l), (l) => errors.push(l))).to.equal(0);
  });

  it('answers 1 and writes nothing on a refusal or a bad option', async () => {
    const errors: string[] = [];
    expect(await main(['--nope'], () => undefined, (l) => errors.push(l))).to.equal(1);
    expect(await main([], () => undefined, (l) => errors.push(l))).to.equal(1);
    expect(await main(['--out'], () => undefined, (l) => errors.push(l))).to.equal(1);
    expect(errors.join('\n')).to.match(/unknown option --nope[\s\S]*no config dir[\s\S]*--out needs a value/);
  });
});
