#!/usr/bin/env node
/**
 * Rewrites the docs block of .gitignore: everything under docs/ is ignored except one
 * folder per package in packages/. Run after adding, removing or renaming a package.
 *
 * Usage:  node scripts/sync-docs-gitignore.mjs
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GITIGNORE = join(ROOT, '.gitignore');
const START = '# docs-packages-start: generated by `npm run docs:gitignore`, do not edit';
const END = '# docs-packages-end';

const packages = readdirSync(join(ROOT, 'packages'), { withFileTypes: true })
  .filter((e) => e.isDirectory() && existsSync(join(ROOT, 'packages', e.name, 'package.json')))
  .map((e) => e.name)
  .sort();

const source = readFileSync(GITIGNORE, 'utf8');
const eol = source.includes('\r\n') ? '\r\n' : '\n';
const block = [START, '/docs/*', ...packages.map((name) => `!/docs/${name}/`), END].join(eol);

const start = source.indexOf(START);
const end = source.indexOf(END);
let next;
if (start !== -1 && end > start) {
  next = source.slice(0, start) + block + source.slice(end + END.length);
} else {
  next = source.replace(/(\r?\n)*$/, '') + eol + eol + block + eol;
}

if (next !== source) {
  writeFileSync(GITIGNORE, next, 'utf8');
  console.log(`.gitignore: docs/ allows ${packages.length} package folders`);
} else {
  console.log('.gitignore: docs block up to date');
}
